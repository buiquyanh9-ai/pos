import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

export type DB = DatabaseSync;

const SCHEMA = `
PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS products (
  id         TEXT PRIMARY KEY,
  sku        TEXT UNIQUE,
  barcode    TEXT,
  name       TEXT NOT NULL,
  category   TEXT NOT NULL DEFAULT '',
  price      INTEGER NOT NULL CHECK (price >= 0),
  stock      INTEGER NOT NULL DEFAULT 0,
  active     INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_products_barcode ON products(barcode);

CREATE TABLE IF NOT EXISTS orders (
  id             TEXT PRIMARY KEY,           -- generated by the POS (idempotent upload)
  number         TEXT NOT NULL,
  device_id      TEXT NOT NULL,
  cashier        TEXT NOT NULL DEFAULT '',
  subtotal       INTEGER NOT NULL,
  discount       INTEGER NOT NULL DEFAULT 0,
  total          INTEGER NOT NULL,
  payment_method TEXT NOT NULL CHECK (payment_method IN ('cash','card','transfer')),
  paid           INTEGER NOT NULL,
  change_due     INTEGER NOT NULL DEFAULT 0,
  status         TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('completed','voided')),
  created_at     TEXT NOT NULL,              -- time of sale on the device
  received_at    TEXT NOT NULL               -- time the server stored it
);
CREATE INDEX IF NOT EXISTS idx_orders_created ON orders(created_at);

CREATE TABLE IF NOT EXISTS order_items (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  order_id   TEXT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id TEXT,
  name       TEXT NOT NULL,
  price      INTEGER NOT NULL,
  qty        INTEGER NOT NULL CHECK (qty > 0),
  line_total INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_items_order ON order_items(order_id);

CREATE TABLE IF NOT EXISTS devices (
  id         TEXT PRIMARY KEY,
  name       TEXT NOT NULL,
  kind       TEXT NOT NULL DEFAULT 'pos',
  app_version TEXT,
  last_seen  TEXT NOT NULL
);

-- Append-only change feed. ShopFlow Boss pulls from here with a cursor (seq).
CREATE TABLE IF NOT EXISTS change_log (
  seq       INTEGER PRIMARY KEY AUTOINCREMENT,
  entity    TEXT NOT NULL,                   -- 'product' | 'order'
  entity_id TEXT NOT NULL,
  op        TEXT NOT NULL,                   -- 'upsert' | 'delete'
  at        TEXT NOT NULL
);
`;

export function openDb(path: string): DB {
  if (path !== ':memory:') mkdirSync(dirname(path), { recursive: true });
  const db = new DatabaseSync(path);
  db.exec(SCHEMA);
  migrate(db);
  return db;
}

// Additive column migrations: safe to run on every start, existing databases keep their data.
const COLUMNS: [table: string, column: string, ddl: string][] = [
  ['products', 'image_url', "TEXT"],
  ['orders', 'order_type', "TEXT NOT NULL DEFAULT 'dine_in'"],
  ['orders', 'table_name', "TEXT NOT NULL DEFAULT ''"],
  ['orders', 'note', "TEXT NOT NULL DEFAULT ''"],
  ['order_items', 'note', "TEXT NOT NULL DEFAULT ''"],
];

function migrate(db: DB) {
  for (const [table, column, ddl] of COLUMNS) {
    const cols = db.prepare(`PRAGMA table_info(${table})`).all() as { name: string }[];
    if (!cols.some((c) => c.name === column)) db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${ddl}`);
  }
}

export function now() {
  return new Date().toISOString();
}

export function logChange(db: DB, entity: 'product' | 'order', entityId: string, op: 'upsert' | 'delete') {
  db.prepare('INSERT INTO change_log (entity, entity_id, op, at) VALUES (?, ?, ?, ?)').run(entity, entityId, op, now());
}

/** Run fn inside a transaction; rolls back on throw. */
export function tx<T>(db: DB, fn: () => T): T {
  db.exec('BEGIN IMMEDIATE');
  try {
    const result = fn();
    db.exec('COMMIT');
    return result;
  } catch (err) {
    db.exec('ROLLBACK');
    throw err;
  }
}

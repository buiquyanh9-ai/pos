function migrate(db: DB) {
  // The inventory module was removed (25/11/2026): drop its tables from older databases.
  // Children first so foreign keys never block the drop.
  for (const t of ['option_recipes', 'recipes', 'purchase_lines', 'purchase_requests', 'stocktake_lines', 'stocktakes',
    'kitchen_lines', 'kitchen_sessions', 'stock_moves', 'inventory_items', 'suppliers']) db.exec(`DROP TABLE IF EXISTS ${t}`);
  db.exec("DELETE FROM notification_prefs WHERE type LIKE 'stock.%' OR type LIKE 'purchase.%' OR type = 'kitchen.closed'");
  // v1 created `orders` with CHECK constraints that reject 'refunded' and 'qr'. Rebuild it once.
  const ordersSql = (db.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name='orders'").get()?.sql as string) ?? '';
  if (ordersSql.includes('CHECK (payment_method IN')) {
    const v1Cols = (db.prepare('PRAGMA table_info(orders)').all() as { name: string }[]).map((c) => c.name).join(', ');
    db.exec('PRAGMA foreign_keys = OFF');
    db.exec('PRAGMA legacy_alter_table = ON'); // keep order_items' FK pointing at "orders"
    db.exec('BEGIN');
    db.exec('ALTER TABLE orders RENAME TO orders_v1');
    db.exec(ORDERS_DDL);
    for (const [table, column, ddl] of COLUMNS) if (table === 'orders') db.exec(`ALTER TABLE orders ADD COLUMN ${column} ${ddl}`);
    db.exec(`INSERT INTO orders (${v1Cols}) SELECT ${v1Cols} FROM orders_v1`);
    db.exec('DROP TABLE orders_v1');
    db.exec('COMMIT');
    db.exec('PRAGMA legacy_alter_table = OFF');
    db.exec('PRAGMA foreign_keys = ON');
  }
  for (const [table, column, ddl] of COLUMNS) {
    const cols = db.prepare(`PRAGMA table_info(${table})`).all() as { name: string }[];
    if (!cols.some((c) => c.name === column)) db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${ddl}`);
  }
  db.exec('CREATE INDEX IF NOT EXISTS idx_orders_shift ON orders(shift_id)');
  // The stock-staff role was removed: those accounts become cashiers.
  db.exec("UPDATE users SET role = 'cashier' WHERE role = 'stock'");
  // QR payments are bank transfers: merge them so reports show one method.
  db.exec("UPDATE orders SET payment_method = 'transfer' WHERE payment_method = 'qr'");
  // v1 -> v2: build categories from the legacy text column.
  const orphan = db.prepare("SELECT DISTINCT category FROM products WHERE category_id IS NULL AND category <> ''").all();
  for (const r of orphan) {
    const name = r.category as string;
    let cat = db.prepare('SELECT id FROM categories WHERE name = ?').get(name);
    if (!cat) {
      const id = `c-${slug(name)}`;
      db.prepare('INSERT OR IGNORE INTO categories (id, name, sort) VALUES (?, ?, (SELECT COALESCE(MAX(sort),0)+1 FROM categories))').run(id, name);
      cat = db.prepare('SELECT id FROM categories WHERE name = ?').get(name);
    }
    db.prepare('UPDATE products SET category_id = ? WHERE category = ? AND category_id IS NULL').run(cat!.id as string, name);
  }
}

export function slug(s: string) {
  return (
    s
      .normalize('NFD')
      .replace(/[̀-ͯ]/g, '')
      .replace(/đ/gi, 'd')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'x'
  );
}

export function openDb(path: string): DB {
  if (path !== ':memory:') mkdirSync(dirname(path), { recursive: true });
  const db = new DatabaseSync(path);
  db.exec(SCHEMA);
  migrate(db);
  return db;
}

export function now() {
  return new Date().toISOString();
}

export function logChange(db: DB, entity: string, entityId: string, op: 'upsert' | 'delete') {
  db.prepare('INSERT INTO change_log (entity, entity_id, op, at) VALUES (?, ?, ?, ?)').run(entity, entityId, op, now());
}

export function audit(db: DB, userId: string | null, action: string, entity: string, entityId: string | null, data?: unknown) {
  db.prepare('INSERT INTO audit_log (user_id, action, entity, entity_id, data, at) VALUES (?, ?, ?, ?, ?, ?)').run(
    userId,
    action,
    entity,
    entityId,
    data === undefined ? null : JSON.stringify(data),
    now(),
  );
}

let txDepth = 0;
/** Run fn inside a write transaction (BEGIN IMMEDIATE serializes writers); rolls back on throw.
 *  Nested calls join the outer transaction. */
export function tx<T>(db: DB, fn: () => T): T {
  if (txDepth > 0) return fn();
  db.exec('BEGIN IMMEDIATE');
  txDepth++;
  try {
    const result = fn();
    txDepth--;
    db.exec('COMMIT');
    return result;
  } catch (err) {
    txDepth--;
    db.exec('ROLLBACK');
    throw err;
  }
}

export function getSetting(db: DB, key: string): string | undefined {
  return db.prepare('SELECT value FROM settings WHERE key = ?').get(key)?.value as string | undefined;
}
export function setSetting(db: DB, key: string, value: string) {
  db.prepare('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value').run(key, value);
}
